func TestServeDNSApplicationA(t *testing.T) {
	const (
		zone     = "project.edge.example.com."
		target1  = "192.0.2.1"
		target2  = "192.0.2.2"
		resolver = "192.0.2.53"
		subnet   = "198.51.100.0"
	)

	tests := []struct {
		name      string
		host      string
		targets   []string
		ttl       endpoint.TTL
		subnet    string
		tcp       bool
		want      []string
		wantTTL   uint32
		wantRcode int
	}{
		{
			name: "apex addresses and endpoint TTL",
			host: zone, targets: []string{target1, target2, target1}, ttl: 30,
			want: []string{target1, target2}, wantTTL: 30,
		},
		{
			name: "apex uses default TTL when unset",
			host: zone, targets: []string{target1},
			want: []string{target1}, wantTTL: 60,
		},
		{
			name: "apex without healthy targets still exists",
			host: zone,
		},
		{
			name: "apex preserves client subnet on TCP and case insensitive lookup",
			host: strings.ToUpper(zone), targets: []string{target2}, ttl: 15,
			subnet: subnet, tcp: true,
			want: []string{target2}, wantTTL: 15,
		},
		{
			name: "subdomain addresses remain available",
			host: "www." + zone, targets: []string{target1}, ttl: 30,
			want: []string{target1}, wantTTL: 30,
		},
		{
			name: "missing subdomain remains NXDOMAIN",
			host: "missing." + zone, wantRcode: dns.RcodeNameError,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			opts := NewGatewayOpts("", "", "test.mmdb", []string{"country.iso_code"}, 60, 300, []string{zone})
			gw := NewGateway(opts)
			original := k8sctrl.Resources.DNSEndpoint.Lookup
			t.Cleanup(func() { k8sctrl.Resources.DNSEndpoint.Lookup = original })
			lookups := 0
			k8sctrl.Resources.DNSEndpoint.Lookup = func(key string, clientIP net.IP, path string, fields [][]string) k8sctrl.LocalDNSEndpoint {
				lookups++
				assert.True(t, strings.EqualFold(strings.TrimSuffix(tc.host, "."), key), "lookup key: %s", key)
				wantIP := resolver
				if tc.subnet != "" {
					wantIP = tc.subnet
				}
				assert.True(t, net.ParseIP(wantIP).Equal(clientIP), "client IP: %v", clientIP)
				assert.Equal(t, opts.geoDataFilePath, path)
				assert.Equal(t, opts.geoDataFields, fields)
				return k8sctrl.LocalDNSEndpoint{Targets: tc.targets, TTL: tc.ttl}
			}

			query := new(dns.Msg)
			query.SetQuestion(tc.host, dns.TypeA)
			if tc.subnet != "" {
				query.SetEdns0(1232, false)
				query.IsEdns0().Option = append(query.IsEdns0().Option, &dns.EDNS0_SUBNET{
					Code: dns.EDNS0SUBNET, Family: 1, SourceNetmask: 24, Address: net.ParseIP(tc.subnet),
				})
			}
			writer := dnstest.NewRecorder(&test.ResponseWriter{RemoteIP: resolver, TCP: tc.tcp})
			_, err := gw.ServeDNS(context.Background(), writer, query)
			require.NoError(t, err)
			require.NotNil(t, writer.Msg)
			assert.Equal(t, tc.wantRcode, writer.Msg.Rcode)
			assert.Equal(t, query.Question, writer.Msg.Question)
			assert.Equal(t, 1, lookups)
			require.Len(t, writer.Msg.Answer, len(tc.want))
			for i, rr := range writer.Msg.Answer {
				a, ok := rr.(*dns.A)
				require.True(t, ok, "expected A record, got %T", rr)
				assert.Equal(t, tc.want[i], a.A.String())
				assert.Equal(t, strings.ToLower(tc.host), a.Hdr.Name)
				assert.Equal(t, tc.wantTTL, a.Hdr.Ttl)
			}
			if len(tc.want) == 0 {
				require.Len(t, writer.Msg.Ns, 1)
				soa, ok := writer.Msg.Ns[0].(*dns.SOA)
				require.True(t, ok, "expected SOA authority, got %T", writer.Msg.Ns[0])
				assert.True(t, strings.EqualFold(zone, soa.Hdr.Name), "SOA name: %s", soa.Hdr.Name)
			} else {
				assert.Empty(t, writer.Msg.Ns)
			}
		})
	}
}

func TestServeDNSApexOtherTypes(t *testing.T) {
	const zone = "project.edge.example.com."
	for _, qtype := range []uint16{dns.TypeSOA, dns.TypeNS, dns.TypeAAAA, dns.TypeTXT} {
		t.Run(dns.TypeToString[qtype], func(t *testing.T) {
			gw := NewGateway(NewGatewayOpts("", "", "", nil, 60, 300, []string{zone}))
			original := k8sctrl.Resources.DNSEndpoint.Lookup
			t.Cleanup(func() { k8sctrl.Resources.DNSEndpoint.Lookup = original })
			k8sctrl.Resources.DNSEndpoint.Lookup = func(string, net.IP, string, [][]string) k8sctrl.LocalDNSEndpoint {
				t.Fatal("unexpected application lookup")
				return k8sctrl.LocalDNSEndpoint{}
			}
			gw.externalAddrFunc = func(request.Request) []dns.RR {
				return []dns.RR{test.A("ns1.dns." + zone + " 60 IN A 192.0.2.53")}
			}

			query := new(dns.Msg)
			query.SetQuestion(zone, qtype)
			writer := dnstest.NewRecorder(&test.ResponseWriter{})
			_, err := gw.ServeDNS(context.Background(), writer, query)
			require.NoError(t, err)
			require.NotNil(t, writer.Msg)
			assert.Equal(t, dns.RcodeSuccess, writer.Msg.Rcode)
			switch qtype {
			case dns.TypeSOA:
				require.Len(t, writer.Msg.Answer, 1)
				assert.IsType(t, &dns.SOA{}, writer.Msg.Answer[0])
				require.Len(t, writer.Msg.Ns, 1)
				assert.IsType(t, &dns.NS{}, writer.Msg.Ns[0])
			case dns.TypeNS:
				require.Len(t, writer.Msg.Answer, 1)
				assert.Equal(t, "ns1.dns."+zone, writer.Msg.Answer[0].(*dns.NS).Ns)
				require.Len(t, writer.Msg.Extra, 1)
				assert.Equal(t, "ns1.dns."+zone, writer.Msg.Extra[0].Header().Name)
				assert.Equal(t, uint32(300), writer.Msg.Extra[0].Header().Ttl)
				assert.Equal(t, "192.0.2.53", writer.Msg.Extra[0].(*dns.A).A.String())
			default:
				assert.Empty(t, writer.Msg.Answer)
				require.Len(t, writer.Msg.Ns, 1)
				assert.IsType(t, &dns.SOA{}, writer.Msg.Ns[0])
			}
		})
	}
}
